import { describe, it, expect, afterEach, vi } from 'vitest';
import i18next from 'i18next';
import en from '../i18n/locales/en.json';
import he from '../i18n/locales/he.json';
import { WordProblemFactory } from '../engines/ProblemFactory';
import { RandomUtils } from '../engines/utils/ProblemUtils';
import {
    WORD_PROBLEM_TEMPLATES,
    difficultyFromLevel,
    type WordProblemTemplate,
} from '../data/wordProblemTemplates';
// The e2e helper parser is a pure, Playwright-free module (e2e/ is excluded from typecheck/lint
// and from vitest test roots, but importing it from a src test is fine).
import { parseWordProblemAnswer } from '../../e2e/wordProblemParser';

/**
 * F1.1: deterministic coverage for the e2e word-problem answer parser. Every
 * WORD_PROBLEM_TEMPLATES entry is generated by the real WordProblemFactory, rendered through the
 * real en/he resources, and the parser must recover problem.answer from the rendered text alone.
 */

const LOCALES = { en, he } as const;

async function makeT(lng: keyof typeof LOCALES) {
    const instance = i18next.createInstance();
    await instance.init({
        lng,
        fallbackLng: false,
        resources: { [lng]: { translation: LOCALES[lng] } },
        interpolation: { escapeValue: false }, // same as src/i18n.ts
    });
    return instance.t.bind(instance);
}

/** A level that maps to the given difficulty pool (via the real difficultyFromLevel). */
function levelFor(difficulty: WordProblemTemplate['difficulty']): number {
    for (let level = 1; level <= 50; level++) {
        if (difficultyFromLevel(level) === difficulty) return level;
    }
    throw new Error(`no level maps to difficulty ${difficulty}`);
}

/** Force the factory to pick exactly this template, regardless of its recent-ids filter. */
function forceTemplate(template: WordProblemTemplate) {
    (WordProblemFactory as unknown as { recentIds: string[] }).recentIds.length = 0;
    vi.spyOn(RandomUtils, 'pickOne').mockImplementation(<T,>(items: T[]): T => {
        const hit = (items as unknown as WordProblemTemplate[]).find((t) => t.id === template.id);
        if (!hit) throw new Error(`template ${template.id} not in the offered pool`);
        return hit as unknown as T;
    });
}

/** Operand pairs per template: the four range corners plus some random draws. */
function operandPairs(t: WordProblemTemplate): Array<[number, number]> {
    const pairs: Array<[number, number]> = [
        [t.minN1, t.minN2],
        [t.maxN1, t.maxN2],
        [t.minN1, t.maxN2],
        [t.maxN1, t.minN2],
    ];
    for (let i = 0; i < 6; i++) {
        pairs.push([
            RandomUtils.intInclusive(t.minN1, t.maxN1),
            RandomUtils.intInclusive(t.minN2, t.maxN2),
        ]);
    }
    return pairs;
}

describe('parseWordProblemAnswer (e2e helper) against every word-problem template', () => {
    afterEach(() => {
        vi.restoreAllMocks();
    });

    it('covers all templates and every difficulty pool', () => {
        expect(WORD_PROBLEM_TEMPLATES.length).toBeGreaterThanOrEqual(22);
        for (const d of ['easy', 'medium', 'hard'] as const) {
            expect(WORD_PROBLEM_TEMPLATES.some((t) => t.difficulty === d)).toBe(true);
        }
    });

    it('has an en and he string for every template key', () => {
        for (const t of WORD_PROBLEM_TEMPLATES) {
            const key = t.i18nKey.replace(/^wordProblems\./, '');
            expect((en as any).wordProblems[key], `en ${t.i18nKey}`).toBeTruthy();
            expect((he as any).wordProblems[key], `he ${t.i18nKey}`).toBeTruthy();
        }
    });

    for (const locale of ['en', 'he'] as const) {
        describe(`locale ${locale}`, () => {
            for (const template of WORD_PROBLEM_TEMPLATES) {
                it(`${template.difficulty} / ${template.id}: parsed answer equals problem.answer`, async () => {
                    const t = await makeT(locale);
                    const level = levelFor(template.difficulty);
                    const factory = new WordProblemFactory();

                    for (const [n1, n2] of operandPairs(template)) {
                        forceTemplate(template);
                        const problem = factory.generate(level, 'word', { n1, n2 } as any);
                        expect(problem.questionKey).toBe(template.i18nKey);

                        const rendered = t(problem.questionKey, problem.params as Record<string, unknown>) as string;
                        expect(
                            parseWordProblemAnswer(rendered),
                            `${locale} ${template.id} n1=${problem.params.n1} n2=${problem.params.n2}: ${rendered}`,
                        ).toBe(problem.answer);
                    }
                });
            }
        });
    }

    it('returns null when the text has fewer than two numbers', () => {
        expect(parseWordProblemAnswer('no numbers here')).toBeNull();
        expect(parseWordProblemAnswer('only 7 here')).toBeNull();
    });
});
